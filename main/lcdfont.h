#define MAO_UNI     0x8302
#define MING_UNI    0x540D
#define ONE_FONT_BYTES 128

// ==================== LVGL 8.x 正确接口 ====================
static bool get_glyph_dsc(const lv_font_t * font, lv_font_glyph_dsc_t * dsc, uint32_t unicode, uint32_t next)
{
    int idx = -1;
    if (unicode == MAO_UNI) idx = 0;
    if (unicode == MING_UNI) idx = 1;
    if (idx < 0) return false;

    dsc->adv_w = 32;
    dsc->box_w = 32;
    dsc->box_h = 32;
    dsc->ofs_x = 0;
    dsc->ofs_y = 0;
    dsc->bpp   = 1;

    return true;
}

static const uint8_t * get_glyph_bitmap(const lv_font_t * font, uint32_t unicode)
{
    int idx = -1;
    if (unicode == MAO_UNI) idx = 0;
    if (unicode == MING_UNI) idx = 1;
    if (idx < 0) return NULL;

    return &hz32[idx * ONE_FONT_BYTES];
}

